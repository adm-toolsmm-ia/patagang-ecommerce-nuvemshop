// ============================================================================
// UTILITIES
// ============================================================================

const colors = {
  reset: '\x1b[0m',
  red: '\x1b[31m',
  yellow: '\x1b[33m',
  green: '\x1b[32m',
  blue: '\x1b[34m',
  gray: '\x1b[90m',
  boldRed: '\x1b[1;31m',
  boldYellow: '\x1b[1;33m',
  boldGreen: '\x1b[1;32m',
};

function log(color, label, message) {
  console.log(`${colors[color]}[${label}]${colors.reset} ${message}`);
}

function logSeparator() {
  console.log('\n' + '='.repeat(80) + '\n');
}

function globToRegex(glob) {
  return new RegExp(
    '^' +
    glob
      .replace(/\./g, '\\.')
      .replace(/\*/g, '[^/]*')
      .replace(/\*\*/g, '.*') +
    '$'
  );
}

function matchesGlob(filePath, glob) {
  const regex = globToRegex(glob);
  return regex.test(filePath);
}

function getFilesRecursive(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;

  const files = fs.readdirSync(dir);
  files.forEach((file) => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat.isDirectory()) {
      getFilesRecursive(filePath, fileList);
    } else {
      fileList.push(filePath);
    }
  });
  return fileList;
}

// ============================================================================
// VALIDATION FUNCTIONS
// ============================================================================

class ValidationResult {
  constructor() {
    this.errors = [];
    this.warnings = [];
    this.info = [];
  }

  addError(file, line, message, severity = 'CRITICAL') {
    this.errors.push({ file, line, message, severity });
  }

  addWarning(file, line, message) {
    this.warnings.push({ file, line, message });
  }

  addInfo(message) {
    this.info.push(message);
  }

  hasCritical() {
    return this.errors.some((e) => e.severity === 'CRITICAL');
  }

  isEmpty() {
    return this.errors.length === 0 && this.warnings.length === 0;
  }

  print() {
    if (this.errors.length > 0) {
      console.log(`\n${colors.boldRed}❌ CRITICAL VIOLATIONS — Cannot Proceed${colors.reset}`);
      this.errors.forEach((err) => {
        const location = err.line ? `:${err.line}` : '';
        console.log(`\n  ${colors.red}✗ File:${colors.reset} ${err.file}${location}`);
        console.log(`    ${colors.red}Pattern:${colors.reset} ${err.severity} violation`);
        console.log(`    ${colors.red}Issue:${colors.reset} ${err.message}`);
        console.log(`\n    ${colors.gray}💡 Next steps:${colors.reset}`);
        console.log(`       1. Review: NUVEMSHOP_FTP_STANDARDS.md`);
        console.log(`       2. Undo changes: git checkout ${err.file}`);
        console.log(`       3. Ask @architect for guidance (if override needed)`);
        console.log(`       4. Learn recovery: NUVEMSHOP_FTP_VIOLATION_RECOVERY.md`);
      });
    }

    if (this.warnings.length > 0) {
      console.log(`\n${colors.boldYellow}⚠️  WARNINGS${colors.reset}`);
      this.warnings.forEach((warn) => {
        console.log(
          `  ${colors.yellow}⚠${colors.reset} ${warn.file}:${warn.line || '?'} - ${warn.message}`
        );
      });
      console.log(`\n  ${colors.gray}→ Warnings don't block, but review recommended.${colors.reset}`);
    }

    if (this.info.length > 0) {
      console.log(`\n${colors.blue}ℹ️  VALIDATION SUMMARY${colors.reset}`);
      this.info.forEach((inf) => {
        console.log(`  ${inf}`);
      });
    }
  }
}

// Gate 1: Lint Validation
function validateLint(filePath, content) {
  const result = new ValidationResult();
  const ext = path.extname(filePath).slice(1).toLowerCase();

  if (!CONFIG.lint.fileTypes.includes(ext)) {
    return result; // Skip non-supported types
  }

  // Check CSS file size
  if (ext === 'scss' || ext === 'css' || filePath.includes('style')) {
    const sizeInKB = content.length / 1024;
    if (sizeInKB > CONFIG.lint.cssMaxSize / 1024) {
      result.addError(
        filePath,
        null,
        `CSS exceeds 50 KB limit: ${sizeInKB.toFixed(2)} KB`,
        'CRITICAL'
      );
    } else if (sizeInKB > CONFIG.lint.cssWarnSize / 1024) {
      result.addWarning(
        filePath,
        null,
        `CSS approaching limit: ${sizeInKB.toFixed(2)} KB (warn at 45 KB)`
      );
    }
  }

  // Check indentation consistency
  const lines = content.split('\n');
  let indentStyle = null;
  lines.forEach((line, idx) => {
    if (line.trim().length === 0) return; // Skip empty lines

    const match = line.match(/^(\s+)/);
    if (!match) return;

    const spaces = match[1];
    const isTab = spaces.includes('\t');
    const isSpace = spaces.includes(' ') && !isTab;

    if (indentStyle === null) {
      indentStyle = isTab ? 'tab' : 'space';
    } else if (
      (indentStyle === 'tab' && !isTab) ||
      (indentStyle === 'space' && isTab)
    ) {
      // Only warn if mixed significantly
      if (idx > 10) {
        // Don't flag first few lines
        result.addWarning(
          filePath,
          idx + 1,
          `Mixed indentation (${isTab ? 'tabs' : 'spaces'} in ${indentStyle} file)`
        );
      }
    }
  });

  // Check line length
  lines.forEach((line, idx) => {
    if (line.length > CONFIG.lint.maxLineLength) {
      result.addWarning(
        filePath,
        idx + 1,
        `Line exceeds ${CONFIG.lint.maxLineLength} characters: ${line.length} chars`
      );
    }
  });

  return result;
}

// Gate 2: Pattern Validation
function validatePatterns(filePath, content) {
  const result = new ValidationResult();
  const relPath = filePath.replace(/\\/g, '/'); // Normalize path

  for (const [patternName, pattern] of Object.entries(CONFIG.patterns)) {
    if (patternName === 'cssSize') continue; // Handled in Gate 1

    // Check if file matches pattern globs
    const matches = pattern.files.some((glob) => matchesGlob(relPath, glob));
    if (!matches) continue;

    // Check forbidden patterns
    if (pattern.forbidden) {
      pattern.forbidden.forEach((forbid) => {
        if (forbid.regex.test(content)) {
          result.addError(
            filePath,
            null,
            `[${patternName}] Forbidden modification: ${forbid.desc}`,
            pattern.severity
          );
        }
      });
    }
  }

  return result;
}

// ============================================================================
// MAIN VALIDATION ORCHESTRATION
// ============================================================================

function validateThemeFiles() {
  const themeDir = path.resolve(CONFIG.paths.themeDeploy);

  if (!fs.existsSync(themeDir)) {
    log('yellow', 'WARN', `Theme directory not found: ${themeDir}`);
    return new ValidationResult();
  }

  const files = getFilesRecursive(themeDir);
  const combinedResult = new ValidationResult();

  log('blue', 'INFO', `Validating ${files.length} files...`);
  logSeparator();

  files.forEach((filePath) => {
    const content = fs.readFileSync(filePath, 'utf8');

    // Gate 1: Lint
    const lintResult = validateLint(filePath, content);
    combinedResult.errors.push(...lintResult.errors);
    combinedResult.warnings.push(...lintResult.warnings);

    // Gate 2: Pattern
    const patternResult = validatePatterns(filePath, content);
    combinedResult.errors.push(...patternResult.errors);
    combinedResult.warnings.push(...patternResult.warnings);
  });

  // Add summary
  combinedResult.addInfo(
    `✅ Validated ${files.length} files (Gates 1 & 2 complete)`
  );
  combinedResult.addInfo(
    `Errors: ${combinedResult.errors.length}, Warnings: ${combinedResult.warnings.length}`
  );

  return combinedResult;
}

// ============================================================================
// OUTPUT & EXIT
// ============================================================================

function main() {
  const result = validateThemeFiles();

  logSeparator();
  result.print();
  logSeparator();

  if (result.hasCritical()) {
    log('boldRed', 'FAIL', 'Validation failed: Critical violations detected');
    process.exit(2);
  } else if (result.warnings.length > 0) {
    log('boldYellow', 'WARN', 'Validation passed with warnings');
    process.exit(1);
  } else {
    log('boldGreen', 'PASS', 'All validations passed!');
    process.exit(0);
  }
}

// ============================================================================
// EXECUTION
// ============================================================================

if (require.main === module) {
  main();
}

module.exports = { validateThemeFiles, ValidationResult };
